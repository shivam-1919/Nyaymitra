class I18nManager {
  constructor() {
    this.currentLanguage = localStorage.getItem('nyaymitra_language') || 'English';
    this.translations = I18N_TRANSLATIONS;
    this.listeners = [];
  }

  getLanguage() {
    return this.currentLanguage;
  }

  setLanguage(lang) {
    if (!this.translations[lang]) {
      console.warn(`Language ${lang} not found, falling back to English`);
      lang = 'English';
    }
    this.currentLanguage = lang;
    localStorage.setItem('nyaymitra_language', lang);

    // Keep the DOM select dropdown in sync
    const langSelect = document.getElementById('language-select');
    if (langSelect && langSelect.value !== lang) {
      langSelect.value = lang;
    }

    this.translateDOM();
    this.notifyListeners(lang);
  }

  onLanguageChange(callback) {
    if (typeof callback === 'function') {
      this.listeners.push(callback);
    }
  }

  notifyListeners(lang) {
    this.listeners.forEach(cb => {
      try {
        cb(lang);
      } catch (err) {
        console.error('Error in language change listener:', err);
      }
    });
  }

  t(key, fallback = '') {
    const langDict = this.translations[this.currentLanguage] || this.translations['English'];
    if (langDict && langDict[key]) {
      return langDict[key];
    }
    // Fallback to English dictionary if key missing in current language
    const enDict = this.translations['English'];
    if (enDict && enDict[key]) {
      return enDict[key];
    }
    return fallback || key;
  }

  translateDOM(root = document) {
    try {
      // 1. Text translations
      const elements = root.querySelectorAll('[data-i18n]');
      elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        const translation = this.t(key);
        if (!translation) return;

        // Check if element has a dedicated child <span> (e.g. <button><i ...></i><span>Text</span></button>)
        const directSpan = el.querySelector(':scope > span:not([data-i18n])');
        if (directSpan) {
          directSpan.textContent = translation;
        } else if (el.children.length === 0) {
          el.textContent = translation;
        } else {
          // Update text node without deleting icons (i, svg)
          let updated = false;
          for (let i = 0; i < el.childNodes.length; i++) {
            const node = el.childNodes[i];
            if (node.nodeType === Node.TEXT_NODE && node.textContent.trim().length > 0) {
              node.textContent = ' ' + translation + ' ';
              updated = true;
              break;
            }
          }
          if (!updated) {
            const icon = el.querySelector('i, svg');
            if (icon && !el.querySelector('span')) {
              const span = document.createElement('span');
              span.textContent = ' ' + translation;
              el.appendChild(span);
            } else {
              el.textContent = translation;
            }
          }
        }
      });

      // 2. Placeholder translations
      const placeholders = root.querySelectorAll('[data-i18n-placeholder]');
      placeholders.forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        const translation = this.t(key);
        if (translation) {
          el.placeholder = translation;
        }
      });

      // 3. Title / Tooltip translations
      const titles = root.querySelectorAll('[data-i18n-title]');
      titles.forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        const translation = this.t(key);
        if (translation) {
          el.title = translation;
        }
      });

      // 4. Update Document Title
      if (this.currentLanguage === 'Hindi') {
        document.title = "न्यायमित्र • नागरिक कानूनी अधिकार एवं कल्याणकारी योजना पोर्टल";
      } else if (this.currentLanguage === 'Telugu') {
        document.title = "న్యాయమిత్ర • పౌర చట్టపరమైన హక్కులు, RTI కార్యాచరణ మరియు సంక్షేమ పోర్టల్";
      } else if (this.currentLanguage === 'Tamil') {
        document.title = "நியாயமித்ரா • குடிமக்கள் சட்ட உரிமைகள் & நலத்திட்ட போர்டல்";
      } else if (this.currentLanguage === 'Bengali') {
        document.title = "ন্যায়মিত্র • নাগরিক আইনি অধিকার এবং কল্যাণমূলক পোর্টাল";
      } else if (this.currentLanguage === 'Marathi') {
        document.title = "न्यायमित्र • नागरिक कायदेशीर अधिकार व कल्याणकारी योजना पोर्टल";
      } else if (this.currentLanguage === 'Gujarati') {
        document.title = "ન્યાયમિત્ર • નાગરિક કાનૂની અધિકાર અને કલ્યાણકારી યોજના પોર્ટલ";
      } else {
        document.title = "NyayaMitra • Citizen Legal Rights, RTI Action & Welfare Portal";
      }

      if (window.lucide && typeof window.lucide.createIcons === 'function') {
        window.lucide.createIcons();
      }
    } catch (err) {
      console.error("Error in translateDOM:", err);
    }
  }

  getSpeechLangCode() {
    const langMap = {
      'English': 'en-IN',
      'Hindi': 'hi-IN',
      'Hinglish': 'hi-IN',
      'Bengali': 'bn-IN',
      'Marathi': 'mr-IN',
      'Tamil': 'ta-IN',
      'Telugu': 'te-IN',
      'Gujarati': 'gu-IN'
    };
    return langMap[this.currentLanguage] || 'en-IN';
  }
}

// Global instance
window.i18n = new I18nManager();
